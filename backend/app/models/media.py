from typing import Optional
from pydantic import BaseModel, Field


class VideoMetadata(BaseModel):
    """Accurate container and stream metadata probed via FFprobe."""
    duration_seconds: float = Field(..., description="Duration in seconds")
    width: int = Field(..., description="Video frame width in pixels")
    height: int = Field(..., description="Video frame height in pixels")
    fps: float = Field(..., description="Exact frames per second")
    total_frames: int = Field(..., description="Total verified frame count")
    video_codec: str = Field(..., description="Video codec name (e.g., h264, hevc, av1)")
    video_bitrate: Optional[int] = Field(default=None, description="Video bitrate in bits/sec")
    pixel_format: Optional[str] = Field(default=None, description="Pixel format (e.g., yuv420p)")
    has_audio: bool = Field(..., description="True if container contains an audio stream")
    audio_codec: Optional[str] = Field(default=None, description="Audio codec (e.g., aac, opus, pcm_s16le)")
    audio_sample_rate: Optional[int] = Field(default=None, description="Audio sampling rate in Hz")
    audio_channels: Optional[int] = Field(default=None, description="Number of audio channels")
    audio_bitrate: Optional[int] = Field(default=None, description="Audio bitrate in bits/sec")
    file_size_bytes: int = Field(..., description="Raw file size in bytes")


class MediaExtractionResult(BaseModel):
    """Output artifacts generated by lossless demuxing and stem separation."""
    job_id: str
    raw_video_path: str = Field(..., description="Path to original uploaded video")
    lossless_video_path: str = Field(..., description="Path to silent video stream copy (bit-identical quality)")
    extracted_audio_path: str = Field(..., description="Path to raw extracted audio stem")
    vocals_asr_path: str = Field(..., description="Path to 16kHz mono WAV stem optimized for Whisper/ASR")
    vocals_clone_path: str = Field(..., description="Path to 44.1kHz stereo WAV stem optimized for voice cloning")
    background_path: str = Field(..., description="Path to ambient/background audio stem for downstream remixing")
    metadata: VideoMetadata = Field(..., description="Probed media metadata")
    separation_method: str = Field(..., description="Separation strategy used: 'demucs' or 'ffmpeg_fallback'")
